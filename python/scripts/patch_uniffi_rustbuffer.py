"""Patch uniffi-bindgen's generated Python bindings to write byte arrays in one copy.

Usage: python patch_uniffi_rustbuffer.py GENERATED_PY

uniffi-bindgen's RustBuffer builder writes a byte array one Python loop
iteration per byte, so lowering ImageInput.rgba costs w*h*4 iterations per
encode. Replace that loop with one ctypes.memmove for a contiguous
one-dimensional unsigned-byte buffer (bytes, bytearray, memoryview of either),
keeping the generated loop for anything else, so every input writes the same
bytes or raises the same error as before. Exits non-zero if the generated loop
is not found exactly once, so a uniffi upgrade that changes it cannot drop the
patch silently.

Every place that stages chromahash/_uniffi.py runs this step: `mise run
cbuild:python`, the CI (Python) workflow and the Release (PyPI) workflow.
"""

import sys

LOOP = """    def write(self, value):
        with self._reserve(len(value)):
            for i, byte in enumerate(value):
                self.rbuf.data[self.rbuf.len + i] = byte
"""

COPY = """    def write(self, value):
        # Patched by python/scripts/patch_uniffi_rustbuffer.py: one copy, not one
        # iteration per byte.
        try:
            view = memoryview(value)
        except TypeError:
            view = None
        if view is not None and view.ndim == 1 and view.format == "B" and view.contiguous:
            n = view.nbytes
            with self._reserve(n):
                if n:
                    src = value if type(value) is bytes else view.tobytes()
                    dst = ctypes.cast(self.rbuf.data, ctypes.c_void_p).value + self.rbuf.len
                    ctypes.memmove(dst, src, n)
            return
        with self._reserve(len(value)):
            for i, byte in enumerate(value):
                self.rbuf.data[self.rbuf.len + i] = byte
"""


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        sys.exit("usage: patch_uniffi_rustbuffer.py GENERATED_PY")
    path = argv[1]
    # newline="" keeps the generated line endings on every platform.
    with open(path, encoding="utf-8", newline="") as f:
        src = f.read()
    if src.count(LOOP) != 1:
        sys.exit(
            f"patch_uniffi_rustbuffer: the generated byte-array writer in {path} is not the "
            "loop this step replaces; update the patch for this uniffi-bindgen"
        )
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(src.replace(LOOP, COPY))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
